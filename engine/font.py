_GLYPHS = {**_DIGITS, **_LETTERS}
_ADVANCE = _GW + 1.4  # per-character horizontal step in grid units


def text_width(s: str) -> float:
    """Width of a string in grid units (before scaling)."""
    if not s:
        return 0.0
    return len(s) * _ADVANCE - 1.4


def text_polylines(s: str, ox: float, oy: float, height: float,
                   center: bool = False) -> List[Polyline]:
    """Lay out `s` as world-space polylines.

    `height` is the cap height in world units; `ox, oy` is the baseline start
    (bottom-left) unless `center` is set, in which case the string is centred
    horizontally on `ox`.
    """
    s = s.upper()
    scale = height / _GH
    if center:
        ox = ox - (text_width(s) * scale) / 2.0
    out: List[Polyline] = []
    pen = ox
    for ch in s:
        glyph = _GLYPHS.get(ch)
        if glyph:
            for stroke in glyph:
                out.append([(pen + gx * scale, oy + gy * scale)
                            for (gx, gy) in stroke])
        pen += _ADVANCE * scale
    return out
